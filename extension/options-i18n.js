export const UI_MESSAGES = Object.freeze({ en: EN, "zh-CN": ZH_CN, de: DE, fr: FR, it: IT });

export function resolveUiLanguage(preference = "auto", browserLanguage = "en") {
  if (preference !== "auto" && Object.hasOwn(UI_MESSAGES, preference)) return preference;
  const normalized = String(browserLanguage || "en").toLowerCase();
  if (normalized.startsWith("zh")) return "zh-CN";
  for (const language of ["de", "fr", "it"]) {
    if (normalized.startsWith(language)) return language;
  }
  return "en";
}

export function createTranslator(preference = "auto", browserLanguage = "en") {
  const locale = resolveUiLanguage(preference, browserLanguage);
  const messages = UI_MESSAGES[locale];
  return {
    locale,
    t(key, replacements = {}) {
      const template = messages[key] ?? EN[key] ?? key;
      return Object.entries(replacements).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        template
      );
    }
  };
}
